@dataclass(frozen=True)
class Hit:
    """One candidate the rules could not decide, or one reported decision."""

    path: str
    line: int
    column: int
    reason: str
    excerpt: str

    def render(self) -> str:
        return f"{self.path}:{self.line}:{self.column}: {self.reason}: {self.excerpt}"


@dataclass
class FileResult:
    path: str
    rewrites: Counter[str] = field(default_factory=Counter)
    ambiguous: list[Hit] = field(default_factory=list)
    explained: list[Hit] = field(default_factory=list)

    @property
    def changed(self) -> bool:
        return bool(self.rewrites)


def _statement_end(text: str, start: int) -> int:
    """End of the statement that starts at ``start``: the rest of the line, or
    through the bracket that opens on it."""
    depth = 0
    quote = ""
    index = start
    while index < len(text):
        char = text[index]
        if quote:
            if char == "\\":
                index += 1
            elif text.startswith(quote, index):
                index += len(quote) - 1
                quote = ""
        elif char in "\"'":
            quote = char * 3 if text.startswith(char * 3, index) else char
            index += len(quote) - 1
        elif char == "#":
            newline = text.find("\n", index)
            if newline == -1:
                return len(text)
            index = newline - 1
        elif char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == "\n" and depth <= 0:
            return index
        index += 1
    return len(text)


Decision = tuple[str, str]  # (action, rule); action is rewrite | keep | ambiguous


class Rewriter:
    """Decides, for one occurrence of the old name at a time, whether it is
    the package - and rewrites the ones that provably are."""

    def __init__(
        self,
        old: str,
        new: str,
        paths: Iterable[str],
        groups: Iterable[str] = (),
    ) -> None:
        if not re.fullmatch(_IDENT, old) or not re.fullmatch(_IDENT, new):
            raise ValueError("package names must be plain identifiers")
        if old == new or old.lower() != old or new.lower() != new:
            raise ValueError("package names must differ and be lowercase")
        if old in new or new in old:
            raise ValueError("one package name contains the other; a run could not be repeated")
        self.old = old
        self.new = new
        entries: set[str] = set()
        nested: set[str] = set()
        for path in paths:
            parts = path.split("/")
            entries.add(parts[0])
            if len(parts) > 1:
                nested.add(f"{_stem(parts[0])}.{_stem(parts[1])}")
        #: Names directly inside the package directory (``core``, ``__main__.py``).
        self.entries = frozenset(entries)
        #: The same as importable names (``core``, ``__main__``).
        self.modules = frozenset(_stem(entry) for entry in entries)
        #: Two-level importable names (``core.config``, ``ui.web``).
        self.submodules = frozenset(nested)
        self.groups = frozenset(groups) | _KNOWN_GROUPS
        #: Rule names whose every decision is listed (``--explain``).
        self.explain: frozenset[str] = frozenset()
        escaped = re.escape(old)
        # A candidate: the lowercase name with no letter or digit on either
        # side. ``\b<old>`` inside a regular expression counts as a boundary.
        self._token = re.compile(rf"(?:(?<![A-Za-z0-9])|(?<=\\b)){escaped}(?![A-Za-z0-9])")
        # Where a Python file can bind the name as a variable of its own.
        self._binding = re.compile(
            rf"(?<![.\w\"'/]){escaped}\s*(?:=[^=]|:|,|\)|\bin\b)|\bas\s+{escaped}\b"
            rf"|\b(?:def|class|for)\s+{escaped}\b|[(,]\s*\*{{0,2}}{escaped}\s*[,):=]"
        )
        # A path below the package that names a file which is not there.
        self._made_up_path = re.compile(
            rf"(?<![A-Za-z0-9_./\\-]){escaped}/([A-Za-z0-9_]+)[A-Za-z0-9_./-]*"
            rf"\.(?:{_SOURCE_SUFFIXES})\b"
            rf"|[\"']{escaped}[\"']\s*/\s*[\"']([A-Za-z0-9_]+)"
        )
        self._legacy = [
            (re.compile(entry.pattern.format(old=escaped)), entry.name)
            for entry in LEGACY_IDENTIFIERS
            if entry.pattern
        ]
        self._frozen = _for_packages((frozen.glob for frozen in FROZEN_FILES), old, new)
        self._kept_prefixes = _for_packages((kept.glob for kept in UNRESOLVED_PATHS_KEPT), old, new)

    # ----- construction from a checkout

    @classmethod
    def from_tree(cls, root: Path, old: str, new: str) -> Rewriter:
        """Read the package's layout and entry-point groups from ``root``.

        Both directories count, so a run before the move, a run after it and a
        replay on a branch that added a module all resolve the same names.
        """
        paths = [
            path.split("/", 1)[1]
            for path, _mode in tracked_files(root)
            if path.startswith((old + "/", new + "/"))
        ]
        groups: set[str] = set()
        pyproject = root / "pyproject.toml"
        if pyproject.is_file():
            text = pyproject.read_text(encoding="utf-8", errors="replace")
            pattern = rf'entry-points\.["\'](?:{re.escape(old)}|{re.escape(new)})\.([A-Za-z0-9_]+)'
            groups.update(re.findall(pattern, text))
        return cls(old, new, paths, groups)

    # ----- paths

    def map_path(self, path: str) -> str:
        """Where a tracked path lives after the move."""
        if path.startswith(self.old + "/"):
            return self.new + path[len(self.old) :]
        return path

    def is_frozen(self, path: str) -> bool:
        return any(fnmatch.fnmatchcase(path, pattern) for pattern in self._frozen)

    def keeps_unresolved_paths(self, path: str) -> bool:
        return any(fnmatch.fnmatchcase(path, pattern) for pattern in self._kept_prefixes)

    def resolves(self, name: str) -> bool:
        """True when ``name`` is an entry of the package directory."""
        name = name.rstrip(".")
        return name in self.entries or name in self.modules

    # ----- one file

    def transform(self, path: str, data: bytes) -> bytes:
        """The rewritten bytes of one file (unchanged when nothing applies)."""
        return self.rewrite(path, data)[0]

    def rewrite(self, path: str, data: bytes) -> tuple[bytes, FileResult]:
        result = FileResult(path)
        if self.is_frozen(path) or b"\0" in data[:8192] or self.old.encode() not in data:
            return data, result
        if STUB_MARKER.encode() in data[:400]:
            return data, result
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            return data, result
        text = self._line_rules(path, text, result)
        state = _FileState(self, path, text)
        pieces: list[str] = []
        cursor = 0
        for match in self._token.finditer(text):
            start, end = match.span()
            action, rule = self._decide(state, start, end)
            if self.explain and (rule in self.explain or "*" in self.explain):
                result.explained.append(state.hit(start, f"{action} [{rule}]"))
            if action == "rewrite":
                pieces.append(text[cursor:start])
                pieces.append(self.new)
                cursor = end
                result.rewrites[rule] += 1
            elif action == "ambiguous":
                result.ambiguous.append(state.hit(start, rule))
        pieces.append(text[cursor:])
        return "".join(pieces).encode("utf-8"), result

    # ----- whole-line rules (the two places where a run adds something)

    def _line_rules(self, path: str, text: str, result: FileResult) -> str:
        old, new = re.escape(self.old), self.new
        name = path.rsplit("/", 1)[-1]
        if name in ("pyproject.toml", "setup.cfg"):
            # The compatibility package ships next to the real one.
            pattern = re.compile(
                rf'^([ \t]*include[ \t]*=[ \t]*\[)([^\]\n]*"{old}\*"[^\]\n]*\])', re.MULTILINE
            )

            def add_package(match: re.Match[str]) -> str:
                if f'"{new}*"' in match.group(2):
                    return match.group(0)
                result.rewrites["package discovery"] += 1
                return f'{match.group(1)}"{new}*", {match.group(2)}'

            text = pattern.sub(add_package, text)
        if name == "Dockerfile" or name.startswith("Dockerfile."):
            # The image needs both directories: the package and its old name.
            pattern = re.compile(rf"(COPY[ \t]+(?:--\S+[ \t]+)*){old}([ \t]+\./){old}/?[ \t]*\r?")
            lines = text.split("\n")
            for index, line in enumerate(lines):
                match = pattern.fullmatch(line)
                if not match or KEEP_PRAGMA in line:
                    continue
                twin = f"{match.group(1)}{new}{match.group(2)}{new}"
                if index and lines[index - 1].rstrip("\r") == twin:
                    continue
                ending = "\r" if line.endswith("\r") else ""
                lines[index] = f"{twin}{ending}\n{line}"
                result.rewrites["image copy"] += 1
            text = "\n".join(lines)
        return text

    # ----- one occurrence

    def _decide(self, state: _FileState, start: int, end: int) -> Decision:
        text = state.text
        prev = text[start - 1] if start else ""
        nxt = text[end : end + 1]
        line_start, line_end = state.line_span(start)
        # Long single-line files (reports, data) would make every look-around
        # a scan of the whole line.
        before = text[max(line_start, start - 240) : start]
        after = text[end : min(line_end, end + 240)]

        if text.find(KEEP_PRAGMA, line_start, line_end) != -1:
            return "keep", "pragma"
        legacy = state.legacy_at(start, end)
        if legacy:
            return "keep", legacy
        if state.in_legacy_assignment(start):
            return "keep", "legacy lists"
        # <old>_desktop.log, personal-<old>, x_<old>_sig.
        if prev in ("_", "-") or nxt in ("_", "-"):
            return "keep", "compound identifier"
        # .<old> is a data directory or an attribute of something else.
        if prev == ".":
            return "keep", "dotted suffix"
        if text.startswith("://", end) or (nxt == ":" and text[end + 1 : end + 2].isalpha()):
            return "keep", "scheme or storage prefix"

        if nxt == "." or text.startswith(("\\.", "\\\\."), end):
            return self._decide_dotted(state, start, end, before, after)
        if nxt in ("/", "\\"):
            decision = self._decide_path(state, start, end, prev)
            if decision is not None:
                return decision
        if nxt == "*":
            return "keep", "glob"
        return self._decide_bare(state, start, end, prev, before, after)

    def _decide_dotted(
        self, state: _FileState, start: int, end: int, before: str, after: str
    ) -> Decision:
        chain = _CHAIN_RE.match(state.text, end)
        if chain is None:
            tail = after[1:2]
            if tail == "*":
                return "rewrite", "module wildcard"
            if tail in ("<", "{", "["):
                return "ambiguous", "placeholder: a module of the package, or a plugin group"
            quote = state.text[start - 1 : start]
            if state.is_python and quote in ("'", '"') and tail == quote:
                # ``name.startswith("<old>.")``: a guard over imported module
                # names stops guarding once the modules carry the new name.
                return "ambiguous", "quoted prefix: of module names, or of something else"
            return "keep", "end of sentence"
        segments = _CHAIN_SEGMENT_RE.findall(chain.group(1))
        first = segments[0]
        dunder = first.startswith("__") and first.endswith("__")
        if not dunder and first not in self.modules:
            return "keep", "not a module of the package"
        if state.is_local_name(start):
            return "ambiguous", "a local variable carries the package's name here"
        if dunder:
            return "rewrite", "package attribute"
        if state.is_web:
            if len(segments) > 1 and f"{first}.{segments[1]}" in self.submodules:
                return "rewrite", "module path"
            return "keep", "web source: storage key or group"
        if len(segments) == 1 and first in self.groups:
            if state.text.startswith(".*", chain.end()):
                return "rewrite", "module wildcard"
            return self._decide_group_or_module(state, start, before, chain.end())
        return "rewrite", "module path"

    def _decide_group_or_module(
        self, state: _FileState, start: int, before: str, chain_end: int
    ) -> Decision:
        """``<old>.brain`` is a plugin group AND a module; context tells."""
        tail = state.text[chain_end : chain_end + 16]
        if _IMPORT_STMT_RE.search(before) or re.match(r"\s+import\b", tail):
            return "rewrite", "import"
        if re.match(rf":{_IDENT}", tail):
            return "rewrite", "entry-point target"
        if _IMPORTING_CALL_RE.search(before) or _DASH_M_RE.search(before):
            return "rewrite", "importable name"
        if state.is_python_code_token(start):
            return "rewrite", "module path"
        line = state.line(start)
        if _GROUP_WORD_RE.search(line):
            return "keep", "entry-point groups"
        if _IMPORT_WORD_RE.search(line) or state.has_module_path(line):
            return "ambiguous", "plugin group or module of the same name"
        return "keep", "entry-point groups"

    def _decide_path(self, state: _FileState, start: int, end: int, prev: str) -> Decision | None:
        text = state.text
        separator = re.match(r"/|\\{1,2}", text[end : end + 2])
        if separator is None:
            return None
        rest_at = end + separator.end()
        rest = text[rest_at : rest_at + 160]
        segment = _SEGMENT_RE.match(rest)
        name = segment.group(0).rstrip(".") if segment else ""
        if name and self.resolves(name):
            return "rewrite", "package path"
        if separator.group(0) == "\\" and re.match(r"[bBsSdDwWnrtAZ.()\[\]|$^?+*]", rest):
            return None  # ``<old>\b`` in a regular expression, ``<old>\n`` in a string
        if state.is_web:
            return "keep", "web source: tool prefix"
        if self.keeps_unresolved_paths(state.path):
            return "keep", "prefix of another kind"
        # ``a/<old>/x.py`` and ``b/<old>/x.py`` in a diff are the path itself.
        in_diff = re.search(r"(?:^|[\s\"'`])[ab]/$", text[max(0, start - 3) : start]) is not None
        below_another = prev in ("/", "\\") and not in_diff
        if rest.startswith("..."):
            return "rewrite", "package path"
        if not name:
            opener = rest[:1]
            if below_another:
                return "ambiguous", "directory of this name below another directory"
            if opener == "{":
                first = re.match(r"\{([A-Za-z0-9_]+),", rest)
                if first and self.resolves(first.group(1)):
                    return "rewrite", "package path"
            if opener in ("{", "<", "$", "%"):
                return "ambiguous", "placeholder below the name: a package path, or another prefix"
            return "rewrite", "package directory"
        if below_another:
            return "keep", "directory of this name elsewhere"
        token = _PATH_TOKEN_RE.match(rest).group(0).rstrip(".")  # type: ignore[union-attr]
        if re.search(rf"\.(?:{_SOURCE_SUFFIXES})$", token):
            return "rewrite", "package path (file not in this tree)"
        if (
            re.fullmatch(_IDENT, name)
            and rest[len(name) : len(name) + 1] in ("/", '"', "'", "`")
            and state.makes_up_package_paths()
        ):
            return "rewrite", "package path (file not in this tree)"
        return "ambiguous", f"{self.old}/{name} is not in the package: a path, or another prefix"

    def _decide_bare(
        self, state: _FileState, start: int, end: int, prev: str, before: str, after: str
    ) -> Decision:
        if state.is_local_name(start):
            return "keep", "local variable"
        if _IMPORT_STMT_RE.search(before) and not re.match(r"\s*[-/]", after):
            if _FROM_RE.search(before) and not re.match(r"\s+import\b", after):
                # ``"from <old>"`` with nothing else in the quotes is the start
                # of an import statement a guard tests for; with other words
                # around it ("a message from <old>") it is prose.
                opened = re.search(r"([\"'`])from\s+$", before)
                if opened is None or after[:1] != opened.group(1):
                    return "keep", "name"
            return "rewrite", "import"
        if _IMPORT_REGEX_RE.search(before):
            return "rewrite", "import"
        if _DASH_M_RE.search(before):
            return "rewrite", "module to run"
        if prev in ("'", '"') and after[:1] == prev:
            return self._decide_quoted(state, start, end, before)
        if _TOOL_DIR_RE.search(before) and re.match(r"(?:[\s\"'`,)\]]|$)", after):
            return "rewrite", "directory argument"
        if state.toml_section(start) in _PACKAGE_DATA_SECTIONS:
            if not before.strip() and re.match(r"\s*=", after):
                return "rewrite", "package data key"
        if state.imports_package() and state.is_python_code_token(start):
            # ``import <old>`` ... ``setattr(<old>, name, value)``.
            return "rewrite", "package object"
        return "keep", "name"

    def _decide_quoted(self, state: _FileState, start: int, end: int, before: str) -> Decision:
        """``"<old>"`` exactly: a path segment, an importable name, or a name."""
        if _IMPORTING_CALL_RE.search(before):
            return "rewrite", "importable name"
        if _DIRECTORY_LIST_RE.search(before):
            return "rewrite", "directory list"
        if state.looks_up_package_data(before):
            return "rewrite", "package data key"
        if _PREFIX_TEST_RE.search(before):
            return "ambiguous", "prefix test: on module names, or on something else"
        text = state.text
        # What stands left of the quote, across a line break.
        left = text[max(0, start - 200) : start - 1]
        if _DASH_M_LEFT_RE.search(left):
            return "rewrite", "module to run"
        follower = _FOLLOWER_RE.match(text, end + 1, end + 200)
        if follower and follower.group(1) == "," and not _JOIN_CALL_RE.search(before):
            follower = None  # a list of names, not the arguments of a path join
        if follower and self.resolves(follower.group(2)):
            return "rewrite", "path segment"
        joined = _JOIN_LEFT_RE.search(left)  # root / "<old>"
        if joined is None:
            return "keep", "name"
        by_comma = left.rstrip().endswith(",")
        if by_comma and not _JOIN_CALL_RE.search(state.line(start)):
            return "keep", "name"
        if joined.group(1) in ("'", '"') or _BIN_OPERAND_RE.search(left):
            # home / ".config" / "<old>", bin_dir / "<old>": a folder or a
            # command of that name somewhere else.
            return "keep", "file or folder of that name elsewhere"
        if by_comma and follower is None:
            return "ambiguous", "last argument of a path join: the package, or another folder"
        return "rewrite", "path segment"


def _stem(entry: str) -> str:
    return entry[:-3] if entry.endswith(".py") else entry


def _for_packages(globs: Iterable[str], old: str, new: str) -> list[str]:
    return [
        pattern.replace("{pkg}", package)
        for pattern in globs
        for package in ((old, new) if "{pkg}" in pattern else ("",))
    ]


class _FileState:
    """Lazy per-file facts the rules ask for."""

    def __init__(self, rewriter: Rewriter, path: str, text: str) -> None:
        self.rewriter = rewriter
        self.path = path
        self.text = text
        self.name = path.rsplit("/", 1)[-1]
        suffix = os.path.splitext(self.name)[1].lower()
        self.is_python = suffix in (".py", ".pyi", ".spec")
        self.is_web = suffix in _WEB_SUFFIXES
        self._legacy_spans: list[tuple[int, int, str]] | None = None
        self._assign_spans: list[tuple[int, int]] | None = None
        self._sections: list[tuple[int, str]] | None = None
        self._locals: frozenset[int] | None = None
        self._names: frozenset[tuple[int, int]] | None = None
        self._line_starts: list[int] | None = None
        self._made_up: bool | None = None
        self._imports: bool | None = None
        self._data_tables: frozenset[str] | None = None

    def line_span(self, index: int) -> tuple[int, int]:
        start = self.text.rfind("\n", 0, index) + 1
        end = self.text.find("\n", index)
        return start, len(self.text) if end == -1 else end

    def line(self, index: int) -> str:
        """The line around an offset, capped for single-line files."""
        start, end = self.line_span(index)
        return self.text[max(start, index - 400) : min(end, index + 400)]

    def position(self, index: int) -> tuple[int, int]:
        """1-based (line, column) of an offset."""
        if self._line_starts is None:
            self._line_starts = [0, *(m.end() for m in re.finditer("\n", self.text))]
        line = bisect.bisect_right(self._line_starts, index)
        return line, index - self._line_starts[line - 1] + 1

    def hit(self, index: int, reason: str) -> Hit:
        line, column = self.position(index)
        start, end = self.line_span(index)
        if end - start > 160:
            start, end = max(start, index - 70), min(end, index + 90)
        return Hit(self.path, line, column, reason, self.text[start:end].strip())

    def legacy_at(self, start: int, end: int) -> str:
        if self._legacy_spans is None:
            self._legacy_spans = sorted(
                (m.start(), m.end(), name)
                for pattern, name in self.rewriter._legacy
                for m in pattern.finditer(self.text)
            )
        spans = self._legacy_spans
        # Spans are short and begin at or just before the candidate.
        index = bisect.bisect_right(spans, (start, len(self.text), ""))
        for span_start, span_end, name in reversed(spans[max(0, index - 8) : index]):
            if span_start <= start and end <= span_end:
                return name
        return ""

    def in_legacy_assignment(self, index: int) -> bool:
        if self._assign_spans is None:
            self._assign_spans = [
                (m.start(), _statement_end(self.text, m.end()))
                for m in _LEGACY_ASSIGN_RE.finditer(self.text)
            ]
        return any(start <= index < end for start, end in self._assign_spans)

    def toml_section(self, index: int) -> str:
        if not self.name.endswith(".toml"):
            return ""
        if self._sections is None:
            self._sections = [
                (m.start(), m.group(1).strip()) for m in _TOML_SECTION_RE.finditer(self.text)
            ]
        current = ""
        for start, name in self._sections:
            if start > index:
                break
            current = name
        return current

    def has_module_path(self, line: str) -> bool:
        """True when ``line`` names a module at least two levels deep."""
        rewriter = self.rewriter
        # Either name: the answer must not change once the line is half rewritten.
        package = rf"(?:{re.escape(rewriter.old)}|{re.escape(rewriter.new)})"
        for match in re.finditer(rf"{package}\.({_IDENT})\.({_IDENT})", line):
            if f"{match.group(1)}.{match.group(2)}" in rewriter.submodules:
                return True
        return False

    def makes_up_package_paths(self) -> bool:
        """True when the file talks about files of the package that do not
        exist (a test that builds its own small tree): then every path below
        the name is one of them, and all of them are rewritten alike."""
        if self._made_up is None:
            rewriter = self.rewriter
            self._made_up = any(
                not rewriter.resolves(match.group(1) or match.group(2))
                for match in rewriter._made_up_path.finditer(self.text)
            )
        return self._made_up

    def _parse(self) -> ast.AST | None:
        try:
            return ast.parse(self.text.lstrip("﻿"))
        except (SyntaxError, ValueError):
            return None

    def _local_lines(self) -> frozenset[int]:
        """Lines on which a LOCAL variable named like the package is read."""
        if self._locals is None:
            lines: set[int] = set()
            old = self.rewriter.old
            # Parsing every file costs more than the whole rest of a run; a
            # file can only bind the name where this cheap pattern matches.
            if self.is_python and self.rewriter._binding.search(self.text):
                tree = self._parse()
                bound = False
                loads: list[int] = []
                for node in ast.walk(tree) if tree is not None else ():
                    if isinstance(node, ast.Name) and node.id == old:
                        if isinstance(node.ctx, ast.Load):
                            loads.append(node.lineno)
                        else:
                            bound = True
                    elif isinstance(node, ast.arg) and node.arg == old:
                        bound = True
                    elif isinstance(node, ast.alias) and node.asname == old:
                        bound = True
                    elif isinstance(node, ast.ExceptHandler) and node.name == old:
                        bound = True
                    elif (
                        isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
                        and node.name == old
                    ):
                        bound = True
                if bound:
                    lines.update(loads)
            self._locals = frozenset(lines)
        return self._locals

    def is_local_name(self, index: int) -> bool:
        if not self.is_python:
            return False
        lines = self._local_lines()
        return bool(lines) and self.position(index)[0] in lines

    def is_python_code_token(self, index: int) -> bool:
        """True when the occurrence is a name in Python code, not text in a
        string or a comment."""
        if not self.is_python:
            return False
        if self._names is None:
            tree = self._parse()
            old = self.rewriter.old
            self._names = frozenset(
                (node.lineno, node.col_offset)
                for node in (ast.walk(tree) if tree is not None else ())
                if isinstance(node, ast.Name) and node.id == old
            )
        line, column = self.position(index)
        # The parser counts columns in UTF-8 bytes.
        offset = len(self.text[index - column + 1 : index].encode("utf-8"))
        return (line, offset) in self._names

    def looks_up_package_data(self, before: str) -> bool:
        """True when the quoted name after ``before`` is a key looked up in
        setuptools' package-data table, in one expression or through a
        variable this file assigned the table to."""
        if _PACKAGE_DATA_LOOKUP_RE.search(before):
            return True
        if self._data_tables is None:
            names = _PACKAGE_DATA_ASSIGN_RE.findall(self.text) if self.is_python else ()
            self._data_tables = frozenset(names)
        lookup = _LOOKUP_ON_NAME_RE.search(before)
        return lookup is not None and lookup.group(1) in self._data_tables

    def imports_package(self) -> bool:
        """True when the file binds the package's own name with an import."""
        if self._imports is None:
            pattern = (
                rf"^[ \t]*import[ \t]+(?:[\w.]+[ \t]*,[ \t]*)*{re.escape(self.rewriter.old)}\b"
            )
            self._imports = self.is_python and re.search(pattern, self.text, re.M) is not None
        return self._imports



#!/usr/bin/env python3
"""Move the Python package to a new directory and rewrite every reference to it.

One mechanical step, so the commit that renames the package is exactly this
script's output and any branch can replay it instead of resolving conflicts::

    python scripts/rename/rewrite_package.py --from jarvis --to dodaios --dry-run
    python scripts/rename/rewrite_package.py --from jarvis --to dodaios
    python scripts/rename/rewrite_package.py --from jarvis --to dodaios --check

What a run does, in order:

1. **Move** every tracked file of ``<from>/`` to ``<to>/`` with ``git mv``
   (the frontend source and its built bundle live inside the package and move
   with it).
2. **Rewrite** the references in every tracked text file: imports, dotted
   module paths (``-m <from>.ui.web.launcher``, ``importlib`` and patch
   targets, entry-point TARGETS, logger names) and filesystem paths
   (``<from>/core/x.py`` in workflows, CI path filters, packaging scripts,
   allowlists, docs).
3. **Write the compatibility package** ``<from>/__init__.py``: old start
   commands and old imports keep working and resolve to the SAME module
   objects as the new name.
4. **Stage** exactly the paths it touched.

Only the lowercase package name is ever a candidate, and only where it is
provably the package: a dotted name is rewritten when its first segment is a
real module of the package, a path when its first segment is a real entry of
the package directory. Everything that merely contains the old name stays -
see ``LEGACY_IDENTIFIERS``, ``FROZEN_FILES`` and ``UNRESOLVED_PATHS_KEPT``, the
tables that say what is deliberately left alone and why. A hit the rules
cannot decide is never touched; ``--dry-run`` lists it with ``file:line`` for
a person to decide, and ``--explain RULE`` lists every decision one rule made.
A line that carries the words ``rename-keep`` is skipped entirely.

The script is one stdlib-only file on purpose: branch integration
(``scripts/ci/agent_integrate.py``) loads the version that produced the move
commit straight from that commit and applies it to a branch's own changes.
"""


# --------------------------------------------------------------------------- git


def _git(root: Path, *args: str, stdin: bytes | None = None) -> subprocess.CompletedProcess[bytes]:
    return subprocess.run(  # noqa: S603
        ["git", *args],  # noqa: S607
        cwd=root,
        input=stdin,
        capture_output=True,
        check=False,
        creationflags=_NO_WINDOW,
    )


def tracked_files(root: Path) -> list[tuple[str, str]]:
    """Every tracked path with its git mode, sorted. Conflict stages collapse."""
    proc = _git(root, "ls-files", "-s", "-z")
    if proc.returncode != 0:
        raise SystemExit(f"not a git checkout: {root}\n{proc.stderr.decode('utf-8', 'replace')}")
    seen: dict[str, str] = {}
    for record in proc.stdout.decode("utf-8", "surrogateescape").split("\0"):
        if not record:
            continue
        meta, _, path = record.partition("\t")
        seen.setdefault(path, meta.split(" ", 1)[0])
    return sorted(seen.items())



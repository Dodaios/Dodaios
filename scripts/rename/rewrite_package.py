@dataclass
class Report:
    moves: list[tuple[str, str]] = field(default_factory=list)
    rewritten: dict[str, Counter[str]] = field(default_factory=dict)
    ambiguous: list[Hit] = field(default_factory=list)
    explained: list[Hit] = field(default_factory=list)
    stubs: list[str] = field(default_factory=list)
    blocked: list[str] = field(default_factory=list)

    @property
    def pending(self) -> bool:
        """True when a run would still change something."""
        return bool(self.moves or self.rewritten or self.stubs)

    def totals(self) -> Counter[str]:
        totals: Counter[str] = Counter()
        for rules in self.rewritten.values():
            totals.update(rules)
        return totals

    def as_json(self) -> dict[str, object]:
        totals = self.totals()
        return {
            "files_moved": len(self.moves),
            "files_rewritten": len(self.rewritten),
            "references_rewritten": sum(totals.values()),
            "references_by_rule": dict(sorted(totals.items())),
            "compatibility_files": self.stubs,
            "ambiguous": [vars(hit) for hit in self.ambiguous],
            "blocked": self.blocked,
            "rewritten": {path: dict(rules) for path, rules in sorted(self.rewritten.items())},
        }


def _read(path: Path) -> bytes | None:
    try:
        return path.read_bytes()
    except OSError:
        return None


def plan(
    root: Path, old: str, new: str, explain: Iterable[str] = ()
) -> tuple[Report, dict[str, bytes]]:
    """Work out everything a run would do, without touching the checkout.

    Returns the report and ``{path after the move: new content}`` for the
    files whose content changes.
    """
    rewriter = Rewriter.from_tree(root, old, new)
    rewriter.explain = frozenset(explain)
    report = Report()
    contents: dict[str, bytes] = {}
    files = tracked_files(root)
    tracked = {path for path, _mode in files}
    for path, mode in files:
        if mode not in ("100644", "100755"):
            continue  # a symlink or a submodule: no text to rewrite, and it stays
        data = _read(root / path)
        if data is None:
            continue  # deleted in the working tree
        target = path
        if path.startswith(old + "/") and STUB_MARKER.encode() not in data[:400]:
            target = rewriter.map_path(path)
            if target in tracked or (root / target).exists():
                report.blocked.append(f"{path} -> {target}: the target already exists")
                continue
            report.moves.append((path, target))
        new_data, result = rewriter.rewrite(path, data)
        report.ambiguous.extend(result.ambiguous)
        report.explained.extend(result.explained)
        if result.changed and new_data != data:
            report.rewritten[target] = result.rewrites
            contents[target] = new_data
    # The compatibility package appears once the real one has left (or is
    # leaving) the old directory; a tree that never had the package gets none.
    if report.moves or any(path.startswith(new + "/") for path in tracked):
        leaving = {source for source, _target in report.moves}
        for path, content in stub_files(old, new).items():
            current = None if path in leaving else _read(root / path)
            if current is None or current.replace(b"\r\n", b"\n") != content.encode("utf-8"):
                report.stubs.append(path)
    return report, contents


def _move(root: Path, old: str, new: str, moves: list[tuple[str, str]]) -> None:
    """Move the tracked files with as few ``git mv`` calls as the checkout
    allows: a whole directory wherever its target is still free (untracked
    caches and ``node_modules`` ride along), its children one by one where a
    leftover directory is already in the way."""
    if not moves:
        return
    leaving = {source for source, _target in moves}
    staying = {
        path
        for path, _mode in tracked_files(root)
        if path.startswith(old + "/") and path not in leaving
    }

    def move(source: str, target: str) -> None:
        below = source + "/"
        is_file = source in leaving
        whole = is_file or not any(path.startswith(below) for path in staying)
        if whole and not (root / target).exists():
            (root / target).parent.mkdir(parents=True, exist_ok=True)
            proc = _git(root, "mv", "--", source, target)
            if proc.returncode == 0:
                return
            reason = proc.stderr.decode("utf-8", "replace").strip()
            if is_file:
                raise SystemExit(f"git mv {source} {target} failed: {reason}")
            print(f"[rename] {source}/ did not move in one step ({reason}); going deeper")
        elif is_file:
            raise SystemExit(f"cannot move {source}: {target} already exists")
        children = sorted(
            {path[len(below) :].split("/", 1)[0] for path in leaving if path.startswith(below)}
        )
        for child in children:
            if (root / source / child).exists():  # a failed rename may have got this far
                move(f"{source}/{child}", f"{target}/{child}")

    move(old, new)


def apply(root: Path, old: str, new: str, *, stage: bool = True) -> Report:
    """Run the codemod on the checkout at ``root``."""
    report, contents = plan(root, old, new)
    if report.blocked:
        return report
    _move(root, old, new, report.moves)
    for path, data in contents.items():
        (root / path).write_bytes(data)
    stubs = stub_files(old, new)
    for path in report.stubs:
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(stubs[path].encode("utf-8"))
    touched = sorted({*contents, *report.stubs})
    if stage and touched:
        # Exactly the paths this run wrote: the checkout may hold other work.
        # --force because tracked files do live below ignored directories.
        proc = _git(
            root,
            "add",
            "--force",
            "--pathspec-from-file=-",
            "--pathspec-file-nul",
            stdin="\0".join(touched).encode("utf-8"),
        )
        if proc.returncode != 0:
            raise SystemExit(f"git add failed: {proc.stderr.decode('utf-8', 'replace')}")
    return report


def _print_report(report: Report, *, verbose: bool, limit: int) -> None:
    if verbose:
        for source, target in report.moves[:limit]:
            print(f"move     {source} -> {target}")
        if len(report.moves) > limit:
            print(f"move     ... and {len(report.moves) - limit} more")
        for path, rules in sorted(report.rewritten.items()):
            detail = ", ".join(f"{rule} x{count}" for rule, count in sorted(rules.items()))
            print(f"rewrite  {path}: {detail}")
        for path in report.stubs:
            print(f"write    {path} (compatibility package)")
    for hit in report.explained:
        print("explain  " + hit.render())
    if report.ambiguous:
        print(f"\nAMBIGUOUS - not touched, a person decides ({len(report.ambiguous)}):")
        for hit in report.ambiguous:
            print("  " + hit.render())
    for line in report.blocked:
        print(f"BLOCKED  {line}")
    totals = report.totals()
    print(
        f"\n{len(report.moves)} file(s) to move, {len(report.rewritten)} file(s) to rewrite "
        f"({sum(totals.values())} reference(s)), {len(report.stubs)} compatibility file(s), "
        f"{len(report.ambiguous)} ambiguous hit(s)."
    )
    for rule, count in sorted(totals.items()):
        print(f"  {count:>6}  {rule}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from", dest="old", required=True, help="Current package directory.")
    parser.add_argument("--to", dest="new", required=True, help="New package directory.")
    parser.add_argument("--root", type=Path, default=None, help="Checkout (default: here).")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="Report only; change nothing.")
    mode.add_argument(
        "--check", action="store_true", help="Exit 1 when a run would still change something."
    )
    parser.add_argument("--no-stage", action="store_true", help="Leave the rewrites unstaged.")
    parser.add_argument("--quiet", action="store_true", help="Totals and ambiguous hits only.")
    parser.add_argument("--json", type=Path, help="Also write the full report to this file.")
    parser.add_argument("--limit", type=int, default=20, help="Moves to list (default 20).")
    parser.add_argument(
        "--explain",
        action="append",
        default=[],
        metavar="RULE",
        help="List every decision made by this rule ('*' for all); repeatable.",
    )
    args = parser.parse_args(argv)
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    top = _git((args.root or Path.cwd()).resolve(), "rev-parse", "--show-toplevel")
    if top.returncode != 0:
        print(f"not a git checkout: {args.root or Path.cwd()}", file=sys.stderr)
        return 2
    root = Path(top.stdout.decode("utf-8").strip())

    if args.dry_run or args.check or args.explain:
        report, _contents = plan(root, args.old, args.new, args.explain)
    else:
        report = apply(root, args.old, args.new, stage=not args.no_stage)
    if args.json:
        args.json.write_text(json.dumps(report.as_json(), indent=2), encoding="utf-8")
    _print_report(report, verbose=not (args.quiet or args.check), limit=args.limit)
    if report.blocked:
        return 2
    if args.check and report.pending:
        print(f"check failed: the tree still refers to the {args.old}/ layout:")
        for source, _target in report.moves[:20]:
            print(f"  {source} (not moved)")
        for path in sorted(report.rewritten)[:40]:
            print(f"  {path}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
